import { registerStorageConformance } from '@earendil-works/pi-durable/testing'
import type { Storage } from '@earendil-works/pi-durable'
import { Client } from 'pg'
import { afterAll, describe, expect, it } from 'vitest'
import { createSchema, openPostgresStorage } from './index.js'

/**
 * The conformance suite runs against a real server: `DATABASE_URL` must point at a disposable database, and every case
 * gets its own table prefix so one case's rows never reach another. Without the variable the file reports nothing
 * instead of failing, because the gates must pass on a machine with no Postgres.
 */
const url = process.env['DATABASE_URL']

if (url === undefined) {
  describe.skip('PostgresStorage (DATABASE_URL is not set)', () => {
    it('is covered against a live server only', () => {})
  })
} else {
  const run = Math.random().toString(36).slice(2, 8)
  let caseIndex = 0
  const prefixes: string[] = []

  const withStorage =
    (cleanup: string[]): ((use: (storage: Storage) => Promise<void>) => Promise<void>) =>
    async (use) => {
      const prefix = `t${run}_${caseIndex++}_`
      prefixes.push(prefix)
      const storage = await openPostgresStorage(url, { prefix })
      const tables = Object.values(createSchema(prefix).tables)
      cleanup.push(...tables)
      try {
        await use(storage)
      } finally {
        await storage.close({} as never)
      }
    }

  const created: string[] = []
  registerStorageConformance(
    {
      describe,
      expect: expect as unknown as Parameters<typeof registerStorageConformance>[0]['expect'],
      it: (name, test, timeoutMs) => it(name, test, timeoutMs ?? 60_000),
    },
    'PostgresStorage',
    (use) => withStorage(created)(use),
  )

  afterAll(async () => {
    if (created.length === 0) return
    const client = new Client({ connectionString: url })
    await client.connect()
    try {
      for (const table of created) {
        // Table names are generated by this file and the storage's own schema, never by a caller.
        const drop = `DROP TABLE IF EXISTS ${table} CASCADE`
        await client.query(drop)
      }
    } finally {
      await client.end()
    }
  }, 60_000)
}
